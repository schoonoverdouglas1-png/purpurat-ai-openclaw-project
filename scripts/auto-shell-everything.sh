#!/usr/bin/env bash
# auto-shell-everything.sh — auto-shell automation for purpurat-ai-openclaw-project.
# Built at Douglas Roy Schoonover's order, Nov 17, 2026:
#   "Do the Google recommendations project recommendations get automation
#    purpurat-ai-openclaw-project make it happen"
#   + "Make your shell scripts permanent first temporary last always"
#   + "auto shell everything"
#   + hatch order (Nov 17, 2026): newest first, oldest last, always.
#
# What it implements:
#   Google recommendations (the labeled structure in the tree Douglas got
#   from Google, Nov 17, 2026): AGENTS.md = core operating manual;
#   SOUL.md = persona/voice/avatar; IDENTITY.md = identity/designations;
#   USER.md = user profile; MEMORY.md = archive; workspace/your_files =
#   governing files + project recommendations; this repo = active public
#   fork + persistence repo.
#   Project recommendations (this repo's README, OpenClaw workspace
#   pattern): SOUL identity/tone, AGENTS operating instructions, USER
#   facts, MEMORY durable + daily logs, IDENTITY name/role, HEARTBEAT
#   schedule, TOOLS notes — plus the standing rules: credit kept,
#   old-with-new, and NO private/personal/medical/credential material in
#   this public repo (MEMORY.md and AGENTS.md here are PUBLIC EDITIONS).
#
# Permanent first, temporary last: this script lives permanently in this
# repo's scripts/ folder, and its report is written permanently into this
# repo's reports/ folder. Nothing is written to /tmp at all.
#
# Non-destructive only: no deletes, no force, no network. The one file it
# refreshes is workspace/MANIFEST.sha256, regenerated by the existing
# scripts/build-ember-workspace.sh exactly as that script is designed to do.
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

LIVE_HOME="${EMBER_HOME:-$HOME}"
STAMP="$(TZ=America/Chicago date '+%Y-%m-%d-%H%M')"
HUMAN_TIME="$(TZ=America/Chicago date '+%Y-%m-%d %H:%M %Z')"
REPORT_DIR="$REPO_ROOT/reports"
REPORT="$REPORT_DIR/auto-shell-$STAMP.md"

FAILURES=0
RESULTS=()

pass() { RESULTS+=("- PASS — $1"); }
fail() { RESULTS+=("- FAIL — $1"); FAILURES=$((FAILURES + 1)); }

# ---------------------------------------------------------------------------
# (a) NEWEST FIRST — Ember's live home, verified against Google's tree
# ---------------------------------------------------------------------------
for f in AGENTS.md SOUL.md IDENTITY.md USER.md MEMORY.md; do
  if [ -f "$LIVE_HOME/$f" ]; then
    size="$(stat -c '%s' "$LIVE_HOME/$f")"
    pass "live home file \`$f\` present — $size bytes (Google's tree: ~/ $f)"
  else
    fail "live home file \`$f\` MISSING at $LIVE_HOME/$f"
  fi
done

if [ -d "$LIVE_HOME/workspace/your_files" ]; then
  pass "live \`workspace/your_files\` present — governing files + project recommendations"
else
  fail "live \`workspace/your_files\` MISSING at $LIVE_HOME/workspace/your_files"
fi

if [ -d "$REPO_ROOT/.git" ]; then
  pass "repo clone present — purpurat-ai-openclaw-project, active public fork + persistence repo ($REPO_ROOT)"
else
  fail "repo clone check FAILED — no .git at $REPO_ROOT"
fi

# Project-pattern files in this repo's workspace (README pattern):
for f in workspace/SOUL.md workspace/AGENTS.md workspace/USER.md workspace/MEMORY.md workspace/IDENTITY.md workspace/HEARTBEAT.md workspace/TOOLS.md; do
  if [ -f "$REPO_ROOT/$f" ]; then
    pass "project-pattern file \`$f\` present in repo workspace"
  else
    fail "project-pattern file \`$f\` MISSING in repo workspace"
  fi
done

# ---------------------------------------------------------------------------
# (b) Build the workspace with the existing script; capture its sha256 verify
# ---------------------------------------------------------------------------
BUILD_OUT="$(bash "$REPO_ROOT/scripts/build-ember-workspace.sh" 2>&1)"
BUILD_RC=$?
OK_COUNT="$(printf '%s\n' "$BUILD_OUT" | grep -c ': OK$' || true)"
MISSING_COUNT="$(printf '%s\n' "$BUILD_OUT" | grep -c '^MISSING' || true)"
if [ "$BUILD_RC" -eq 0 ]; then
  pass "scripts/build-ember-workspace.sh ran clean (exit 0) — sha256 verify: $OK_COUNT files OK"
else
  fail "scripts/build-ember-workspace.sh exited $BUILD_RC — sha256 verify: $OK_COUNT files OK"
fi
if [ "$MISSING_COUNT" -gt 0 ]; then
  fail "build-ember-workspace.sh reported $MISSING_COUNT MISSING workspace file(s)"
fi

# ---------------------------------------------------------------------------
# (c) OLDEST LAST — persistence foundations
# ---------------------------------------------------------------------------
if [ -f "$REPO_ROOT/PERSISTENCE.md" ]; then
  pass "persistence foundation \`PERSISTENCE.md\` present at repo root"
else
  fail "persistence foundation \`PERSISTENCE.md\` MISSING at repo root"
fi

if [ -f "$REPO_ROOT/workspace/PERSISTENCE.md" ]; then
  pass "persistence foundation \`workspace/PERSISTENCE.md\` present"
else
  fail "persistence foundation \`workspace/PERSISTENCE.md\` MISSING"
fi

if [ -f "$REPO_ROOT/workspace/MANIFEST.sha256" ]; then
  pass "persistence foundation \`workspace/MANIFEST.sha256\` present"
  if sha256sum -c "$REPO_ROOT/workspace/MANIFEST.sha256" >/dev/null 2>&1; then
    pass "\`sha256sum -c workspace/MANIFEST.sha256\` passes from repo root"
  else
    fail "\`sha256sum -c workspace/MANIFEST.sha256\` FAILED from repo root"
  fi
else
  fail "persistence foundation \`workspace/MANIFEST.sha256\` MISSING"
fi

# ---------------------------------------------------------------------------
# (d) Write the dated report — permanent place: reports/ inside this repo
# ---------------------------------------------------------------------------
mkdir -p "$REPORT_DIR"
{
  echo "# Auto-Shell Report — $HUMAN_TIME"
  echo
  echo "Run by \`scripts/auto-shell-everything.sh\` in purpurat-ai-openclaw-project,"
  echo "at Douglas Roy Schoonover's order (Nov 17, 2026): Google recommendations +"
  echo "project recommendations, automated; shell permanent first, temporary last;"
  echo "auto shell everything. Checks are listed newest first, oldest last"
  echo "(Douglas's hatch order, Nov 17, 2026)."
  echo
  echo "## Results (newest first, oldest last)"
  echo
  printf '%s\n' "${RESULTS[@]}"
  echo
  if [ "$FAILURES" -eq 0 ]; then
    echo "## Verdict: ALL CHECKS PASS"
  else
    echo "## Verdict: $FAILURES CHECK(S) FAILED"
  fi
  echo
  echo "Non-destructive run: no deletes, no force, no network. The only refreshed"
  echo "file is \`workspace/MANIFEST.sha256\`, regenerated by the existing build script"
  echo "as designed. No private material is read into this public repo — the live"
  echo "home files are checked for presence and size only, never copied here."
} > "$REPORT"

echo "auto-shell: report written to $REPORT"
if [ "$FAILURES" -eq 0 ]; then
  echo "auto-shell: ALL CHECKS PASS"
  exit 0
else
  echo "auto-shell: $FAILURES CHECK(S) FAILED" >&2
  exit 1
fi
